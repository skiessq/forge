import { SubtitleItem, SubtitleStyle, Project } from '../types';

// Convert CSS Hex #RRGGBB or #RGB to ASS &HAABBGGRR
export function hexToAssColor(hex: string, alpha = '00'): string {
  let clean = hex.replace('#', '').trim();
  if (clean.length === 3) {
    clean = clean.split('').map((c) => c + c).join('');
  }
  if (clean.length !== 6) {
    return '&H00FFFFFF&';
  }
  const r = clean.substring(0, 2);
  const g = clean.substring(2, 4);
  const b = clean.substring(4, 6);
  return `&H${alpha}${b}${g}${r}&`;
}

// Convert seconds (e.g. 12.345) to ASS timestamp format H:MM:SS.cc
export function secondsToAssTime(seconds: number): string {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = Math.floor(seconds % 60);
  const cs = Math.round((seconds % 1) * 100);

  const mm = m.toString().padStart(2, '0');
  const ss = s.toString().padStart(2, '0');
  const ccs = (cs >= 100 ? 99 : cs).toString().padStart(2, '0');

  return `${h}:${mm}:${ss}.${ccs}`;
}

export function generateAssSubtitles(project: Project): string {
  const { subtitles, subtitleStyle, canvas } = project;

  const fontName = subtitleStyle.fontFamily || 'Montserrat';
  const fontSize = Math.round(subtitleStyle.fontSize || 54);
  const primaryColor = hexToAssColor(subtitleStyle.primaryColor || '#FFFFFF');
  const highlightColor = hexToAssColor(subtitleStyle.highlightColor || '#FFE600');
  const outlineColor = hexToAssColor(subtitleStyle.outlineColor || '#000000');
  const shadowColor = hexToAssColor(subtitleStyle.shadowColor || '#000000', '80');
  const outlineWidth = subtitleStyle.outlineWidth ?? 4;
  const shadowDistance = subtitleStyle.shadowDistance ?? 2;

  // Alignment: 2 = Bottom-center, 5 = Middle-center, 8 = Top-center
  let alignment = 2;
  let marginV = 220; // default bottom margin for vertical shorts
  let marginL = 60;
  let marginR = 60;

  if (subtitleStyle.horizontalOffset) {
    const hOff = subtitleStyle.horizontalOffset;
    if (hOff > 0) {
      marginL = Math.round(60 + hOff * 2);
      marginR = Math.max(10, Math.round(60 - hOff * 2));
    } else {
      marginR = Math.round(60 + Math.abs(hOff) * 2);
      marginL = Math.max(10, Math.round(60 - Math.abs(hOff) * 2));
    }
  }

  if (subtitleStyle.position === 'top') {
    alignment = 8;
    marginV = 160 + (subtitleStyle.verticalOffset || 0);
  } else if (subtitleStyle.position === 'middle') {
    alignment = 5;
    marginV = subtitleStyle.verticalOffset || 0;
  } else {
    // bottom
    alignment = 2;
    marginV = 220 - (subtitleStyle.verticalOffset || 0);
  }

  const header = `[Script Info]
; Script generated by ClipForge
Title: ClipForge Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: ${canvas.width}
PlayResY: ${canvas.height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${fontName},${fontSize},${primaryColor},${highlightColor},${outlineColor},${shadowColor},-1,0,0,0,100,100,0,0,1,${outlineWidth},${shadowDistance},${alignment},${marginL},${marginR},${marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  const dialogueLines: string[] = [];

  for (const item of subtitles) {
    if (!item.text.trim()) continue;

    const transform = subtitleStyle.textTransform;
    let baseText = item.text.trim();
    if (transform === 'uppercase') baseText = baseText.toUpperCase();
    if (transform === 'lowercase') baseText = baseText.toLowerCase();

    // Karaoke active word animation with individual word color support
    if (subtitleStyle.animation === 'karaoke_highlight' && item.words && item.words.length > 0) {
      for (let i = 0; i < item.words.length; i++) {
        const currentWord = item.words[i];
        const wordStart = secondsToAssTime(currentWord.start);
        const wordEnd = secondsToAssTime(currentWord.end);

        // Build line where word i is highlighted and individual word colors are respected
        const lineParts = item.words.map((w, idx) => {
          let wordStr = w.word;
          if (transform === 'uppercase') wordStr = wordStr.toUpperCase();
          if (transform === 'lowercase') wordStr = wordStr.toLowerCase();

          const customColor = w.color ? hexToAssColor(w.color) : null;

          if (idx === i) {
            const activeColor = customColor || highlightColor;
            return `{\\c${activeColor}\\fscx110\\fscy110}${wordStr}{\\c${primaryColor}\\fscx100\\fscy100}`;
          }
          if (customColor) {
            return `{\\c${customColor}}${wordStr}{\\c${primaryColor}}`;
          }
          return wordStr;
        });

        const lineText = lineParts.join(' ');
        dialogueLines.push(
          `Dialogue: 0,${wordStart},${wordEnd},Default,,0,0,0,,${lineText}`
        );
      }
    } else {
      // Build base text with any custom individual word colors preserved
      let styledText = baseText;
      if (item.words && item.words.length > 0) {
        styledText = item.words
          .map((w) => {
            let wordStr = w.word;
            if (transform === 'uppercase') wordStr = wordStr.toUpperCase();
            if (transform === 'lowercase') wordStr = wordStr.toLowerCase();
            if (w.color) {
              return `{\\c${hexToAssColor(w.color)}}${wordStr}{\\c${primaryColor}}`;
            }
            return wordStr;
          })
          .join(' ');
      }

      const start = secondsToAssTime(item.start);
      const end = secondsToAssTime(item.end);

      if (subtitleStyle.animation === 'pop_in') {
        const popText = `{\\t(0,100,\\fscx112\\fscy112)\\t(100,200,\\fscx100\\fscy100)}${styledText}`;
        dialogueLines.push(`Dialogue: 0,${start},${end},Default,,0,0,0,,${popText}`);
      } else if (subtitleStyle.animation === 'bounce_word') {
        const bounceText = `{\\t(0,120,\\fscy118)\\t(120,240,\\fscy100)}${styledText}`;
        dialogueLines.push(`Dialogue: 0,${start},${end},Default,,0,0,0,,${bounceText}`);
      } else if (subtitleStyle.animation === 'neon_glow') {
        const glowText = `{\\bord6\\shad5}${styledText}`;
        dialogueLines.push(`Dialogue: 0,${start},${end},Default,,0,0,0,,${glowText}`);
      } else if (subtitleStyle.animation === 'fade') {
        const fadeText = `{\\fad(150,150)}${styledText}`;
        dialogueLines.push(`Dialogue: 0,${start},${end},Default,,0,0,0,,${fadeText}`);
      } else {
        // Standard / none
        dialogueLines.push(`Dialogue: 0,${start},${end},Default,,0,0,0,,${styledText}`);
      }
    }
  }

  return header + dialogueLines.join('\n') + '\n';
}

export function exportToSrt(subtitles: SubtitleItem[]): string {
  let srt = '';
  subtitles.forEach((s, idx) => {
    const startH = Math.floor(s.start / 3600).toString().padStart(2, '0');
    const startM = Math.floor((s.start % 3600) / 60).toString().padStart(2, '0');
    const startS = Math.floor(s.start % 60).toString().padStart(2, '0');
    const startMs = Math.round((s.start % 1) * 1000).toString().padStart(3, '0');

    const endH = Math.floor(s.end / 3600).toString().padStart(2, '0');
    const endM = Math.floor((s.end % 3600) / 60).toString().padStart(2, '0');
    const endS = Math.floor(s.end % 60).toString().padStart(2, '0');
    const endMs = Math.round((s.end % 1) * 1000).toString().padStart(3, '0');

    srt += `${idx + 1}\n${startH}:${startM}:${startS},${startMs} --> ${endH}:${endM}:${endS},${endMs}\n${s.text}\n\n`;
  });
  return srt;
}

export function parseSrt(srtText: string): SubtitleItem[] {
  const items: SubtitleItem[] = [];
  const blocks = srtText.trim().split(/\r?\n\r?\n/);

  blocks.forEach((block, idx) => {
    const lines = block.split(/\r?\n/);
    if (lines.length >= 2) {
      const timeLine = lines[1].includes('-->') ? lines[1] : lines[0];
      const textLines = lines.slice(lines.indexOf(timeLine) + 1).join(' ');

      const parts = timeLine.split('-->');
      if (parts.length === 2) {
        const parseTime = (tStr: string) => {
          const [hms, ms] = tStr.trim().replace(',', '.').split('.');
          const [h, m, s] = hms.split(':').map(Number);
          return h * 3600 + m * 60 + s + (Number(ms) || 0) / 1000;
        };

        const start = parseTime(parts[0]);
        const end = parseTime(parts[1]);

        items.push({
          id: `sub_import_${idx + 1}`,
          start,
          end,
          text: textLines.trim(),
        });
      }
    }
  });

  return items;
}
